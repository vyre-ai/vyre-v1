// The editable source of a connector, in Files. connector.toml is generated as real TOML (a legacy JSON main file is still read), actions/<name>.json and tests/<name>.json are one JSON document each,
// and anything else in the folder (transforms.js, README.md, recorded files) is left alone. Reading goes through the ORIGINAL caller's Files capabilities, so what a person may not read is never
// compiled; the read is bounded and checked for races, and a failure says which file and why. Nothing here writes: publishing is a separate, rechecked step.
import { parseToml, TomlError } from "../../../lib/toml.ts";
import type { TomlTable, TomlValue } from "../../../lib/toml.ts";
import { checkEgress, refuse } from "../projections.ts";
import type { ActionDef, ConnectorDef, ConnectorsCtx, Method, Mode, Scope, TestCase } from "../projections.ts";

const MODES: readonly Mode[] = ["api", "mcp", "dwd", "oauth_app", "webhook_only"];
const SCOPES: readonly Scope[] = ["person", "space"];
const METHODS: readonly Method[] = ["GET", "POST", "PUT", "PATCH", "DELETE"];
const AUTH_TYPES = ["none", "api_key", "bearer", "oauth2"] as const;
const NAME = /^[A-Za-z0-9][A-Za-z0-9 _.-]{0,79}$/;
const SLOT = /^[A-Za-z][A-Za-z0-9_]{0,63}$/;
const DOMAIN = /^(?:\*\.)?(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$|^[a-z0-9-]+\.internal$|^localhost$/i;

/** What a read of the source may cost. Beyond any of these the source is refused, never trimmed. */
export const SOURCE_BOUNDS = { files: 200, bytes: 2 * 1024 * 1024, fileBytes: 256 * 1024, depth: 3 } as const;

// ---- TOML out

const esc = (s: string): string => `"${s.replace(/[\\"]/g, "\\$&").replace(/[\u0000-\u001f\u007f]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`)}"`;
const val = (v: unknown): string => {
  if (typeof v === "string") return esc(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `[${v.map(val).join(", ")}]`;
  return `{ ${Object.entries(v as Record<string, unknown>).map(([k, x]) => `${key(k)} = ${val(x)}`).join(", ")} }`;
};
const key = (k: string): string => (/^[A-Za-z0-9_-]+$/.test(k) ? k : esc(k));
const line = (k: string, v: unknown): string => `${key(k)} = ${val(v)}`;

/** connector.toml for a definition (everything but its actions and tests, which are their own files). */
export function generateMain(def: ConnectorDef): string {
  const { actions: _a, tests: _t, auth, secrets, rate, objects, ...top } = def;
  void _a; void _t;
  const out: string[] = ["# Generated by Vyre. Edit it here, then Test, Diff and Publish the connector."];
  for (const [k, v] of Object.entries(top)) if (v !== undefined) out.push(line(k, v));
  out.push("", "[auth]");
  for (const [k, v] of Object.entries(auth)) if (v !== undefined) out.push(line(k, v));
  if (rate) out.push("", "[rate]", line("rps", rate.rps), line("burst", rate.burst));
  for (const s of secrets) out.push("", "[[secrets]]", line("name", s.name), line("description", s.description));
  for (const [name, o] of Object.entries(objects ?? {})) { out.push("", `[objects.${key(name)}]`); for (const [k, v] of Object.entries(o)) if (v !== undefined) out.push(line(k, v)); }
  return `${out.join("\n")}\n`;
}

// ---- reading

type Json = Record<string, unknown>;
const isObj = (v: unknown): v is Json => typeof v === "object" && v !== null && !Array.isArray(v);
const strs = (v: unknown): v is string[] => Array.isArray(v) && v.every((x) => typeof x === "string");
const plain = (v: TomlValue | unknown): unknown => JSON.parse(JSON.stringify(v));

/** The main file as an object: JSON from before this was TOML, or TOML. */
export function parseMain(ctx: ConnectorsCtx, text: string): Json {
  const t = text.trim();
  if (t.startsWith("{")) {
    try { const j: unknown = JSON.parse(t); if (isObj(j)) return j; } catch { /* the message below names it */ }
    return refuse(ctx, "validation.bad_input", "connector.toml looks like JSON but is not valid JSON.");
  }
  try { return plain(parseToml(text) as TomlTable) as Json; }
  catch (e) { return refuse(ctx, "validation.bad_input", `connector.toml is not valid TOML: ${e instanceof TomlError ? e.message : "it could not be read"}.`); }
}

const bad = (ctx: ConnectorsCtx, where: string, why: string): never => refuse(ctx, "validation.bad_input", `${where}: ${why}`);

/** The definition a source describes, held to the rules a publish needs: auth none, API key, bearer or OAuth, declared domains and secrets, actions and recorded tests. */
export function buildDef(ctx: ConnectorsCtx, key: string, main: Json, actionDocs: { path: string; doc: unknown }[], testDocs: { path: string; doc: unknown }[]): ConnectorDef {
  const where = "connector.toml";
  if (typeof main["title"] !== "string" || !main["title"].trim() || main["title"].length > 120) bad(ctx, where, "title is text of up to 120 characters.");
  if (!MODES.includes(main["mode"] as Mode)) bad(ctx, where, `mode is one of ${MODES.join(", ")}.`);
  if (!SCOPES.includes(main["scope"] as Scope)) bad(ctx, where, "scope is person or space.");
  if (typeof main["key"] === "string" && main["key"] !== key) bad(ctx, where, `key is ${main["key"]}, but this folder is the source of ${key}.`);
  const domains = main["domains"] ?? [];
  if (!strs(domains) || domains.length > 50 || !domains.every((d) => DOMAIN.test(d))) bad(ctx, where, "domains are host names like api.example.com or *.example.com, at most 50.");
  const auth = main["auth"] ?? { type: "none" };
  if (!isObj(auth) || !AUTH_TYPES.includes(auth["type"] as never)) bad(ctx, where, `auth.type is one of ${AUTH_TYPES.join(", ")}.`);
  const a = auth as Json;
  for (const k of ["secret", "header", "prefix", "authUrl", "tokenUrl", "clientId", "clientSecret", "revokeUrl"]) if (a[k] !== undefined && typeof a[k] !== "string") bad(ctx, where, `auth.${k} is text.`);
  if (a["scopes"] !== undefined && !strs(a["scopes"])) bad(ctx, where, "auth.scopes is a list of text.");
  if (a["type"] !== "none" && typeof a["secret"] !== "string") bad(ctx, where, "auth.secret names the declared secret that holds the key or token.");
  const secrets = main["secrets"] ?? [];
  if (!Array.isArray(secrets) || secrets.length > 20 || !secrets.every((s) => isObj(s) && typeof s["name"] === "string" && SLOT.test(s["name"]) && typeof s["description"] === "string" && s["description"].length <= 300)) bad(ctx, where, "each secret needs a name (letters, digits and underscores) and a description.");
  const slots = (secrets as { name: string; description: string }[]).map((s) => ({ name: s.name, description: s.description }));
  if (new Set(slots.map((s) => s.name)).size !== slots.length) bad(ctx, where, "two secrets share a name.");
  if (a["type"] !== "none" && !slots.some((s) => s.name === a["secret"])) bad(ctx, where, `auth.secret ${String(a["secret"])} is not one of the declared secrets.`);
  // a client secret is the NAME of a declared secret (kept in the Vault), never its value: a value here would sit in Files readable by everyone who reads the source
  if (a["clientSecret"] !== undefined && !slots.some((s) => s.name === a["clientSecret"])) bad(ctx, where, "auth.clientSecret must name one of the declared secrets, not hold the secret itself.");
  if (a["type"] === "oauth2") for (const k of ["authUrl", "tokenUrl", "revokeUrl"]) if (typeof a[k] === "string" && !checkEgress(a[k] as string, domains).ok) bad(ctx, where, `auth.${k} must be an https address on one of the declared domains.`);
  if (main["rate"] !== undefined && !(isObj(main["rate"]) && Number.isFinite(main["rate"]["rps"]) && Number.isFinite(main["rate"]["burst"]))) bad(ctx, where, "rate needs rps and burst as numbers.");
  for (const k of ["sources", "syncedTypes"]) if (main[k] !== undefined && !strs(main[k])) bad(ctx, where, `${k} is a list of text.`);
  if (main["health"] !== undefined && typeof main["health"] !== "string") bad(ctx, where, "health is text.");
  if (main["objects"] !== undefined && !isObj(main["objects"])) bad(ctx, where, "objects is a table of tables.");

  const actions = actionDocs.map(({ path, doc }): ActionDef => {
    if (!isObj(doc) || typeof doc["name"] !== "string" || !NAME.test(doc["name"])) return bad(ctx, path, "an action has a name of letters, digits, spaces, dots, dashes and underscores.");
    if (path !== `actions/${doc["name"]}.json`) bad(ctx, path, `the file is named ${path.slice(8)} but the action is ${doc["name"]}.`);
    if (doc["method"] !== undefined && !METHODS.includes(doc["method"] as Method)) bad(ctx, path, `method is one of ${METHODS.join(", ")}.`);
    if (doc["url"] !== undefined && (typeof doc["url"] !== "string" || doc["url"].length > 2000)) bad(ctx, path, "url is text.");
    for (const k of ["headers", "query"]) if (doc[k] !== undefined && !(isObj(doc[k]) && Object.values(doc[k] as Json).every((v) => typeof v === "string"))) bad(ctx, path, `${k} is a table of text.`);
    if (doc["output"] !== undefined && typeof doc["output"] !== "string") bad(ctx, path, "output is a JSON pointer.");
    if (doc["write"] !== undefined && typeof doc["write"] !== "boolean") bad(ctx, path, "write is true or false.");
    return doc as unknown as ActionDef;
  });
  if (new Set(actions.map((x) => x.name)).size !== actions.length) bad(ctx, "actions", "two actions share a name.");
  const tests = testDocs.map(({ path, doc }): TestCase => {
    if (!isObj(doc) || typeof doc["name"] !== "string" || !doc["name"] || typeof doc["action"] !== "string") return bad(ctx, path, "a test has a name and the action it runs.");
    if (path !== `tests/${doc["name"]}.json`) bad(ctx, path, `the file is named ${path.slice(6)} but the test is ${doc["name"]}.`);
    if (!Array.isArray(doc["responses"]) || !doc["responses"].every((r) => isObj(r) && typeof r["url"] === "string")) bad(ctx, path, "responses are recorded answers, each with a url.");
    return doc as unknown as TestCase;
  });
  return {
    key, title: main["title"] as string, mode: main["mode"] as Mode, scope: main["scope"] as Scope, version: typeof main["version"] === "string" ? main["version"] : "0.0.0",
    auth: a as unknown as ConnectorDef["auth"], domains, secrets: slots, actions, tests,
    ...(strs(main["sources"]) ? { sources: main["sources"] } : {}), ...(strs(main["syncedTypes"]) ? { syncedTypes: main["syncedTypes"] } : {}),
    ...(typeof main["health"] === "string" ? { health: main["health"] } : {}), ...(main["rate"] ? { rate: main["rate"] as { rps: number; burst: number } } : {}),
    ...(main["objects"] ? { objects: main["objects"] as ConnectorDef["objects"] } : {}),
  };
}

// ---- the source in Files, through the caller

interface Listed { files: { fileId: string; name: string; version: number; size?: number }[]; folders: { folderId: string; name: string }[]; next?: string }
export interface SourceRead { def: ConnectorDef; fingerprint: string }

/** Reads and compiles the source folder. Everything goes through ctx.call (the original caller's Files access); a denied, missing, over-large or changing source is refused with the reason. */
export async function readSource(ctx: ConnectorsCtx, key: string, folderId: string): Promise<SourceRead> {
  const call = ctx.call as (cap: string, input: unknown) => Promise<unknown>;
  const folder = await call("files.folder.get", { folderId }).catch((e: unknown) => refuse(ctx, (e as { error?: { code?: string } })?.error?.code === "validation.not_found" ? "validation.not_found" : "permission.no_grant", `The source folder of ${key} cannot be read: ${(e as { error?: { message?: string } })?.error?.message ?? "it is missing or you may not open it"}.`)) as { folder?: { deletedAt?: unknown } };
  if (!folder?.folder) refuse(ctx, "validation.not_found", `The source folder of ${key} is missing.`);
  let files = 0, bytes = 0;
  const list = async (id: string, depth: number): Promise<{ path: string; fileId: string; version: number; name: string }[]> => {
    if (depth > SOURCE_BOUNDS.depth) refuse(ctx, "validation.too_large", `The source of ${key} is nested too deeply.`);
    const out: { path: string; fileId: string; version: number; name: string }[] = [];
    const page = (await call("files.list", { folder: id, limit: SOURCE_BOUNDS.files + 1 })) as Listed;
    if (page.next !== undefined) refuse(ctx, "validation.too_large", `The source of ${key} has too many files to read.`);
    for (const f of page.files) { if ((f.size ?? 0) > SOURCE_BOUNDS.fileBytes && f.name.endsWith(".json") || (f.size ?? 0) > SOURCE_BOUNDS.fileBytes && f.name === "connector.toml") refuse(ctx, "validation.too_large", `${f.name} is too large to read.`); files += 1; if (files > SOURCE_BOUNDS.files) refuse(ctx, "validation.too_large", `The source of ${key} has more than ${SOURCE_BOUNDS.files} files.`); out.push({ path: f.name, fileId: f.fileId, version: f.version, name: f.name }); }
    for (const sub of page.folders) {
      if (depth === 0 && (sub.name === "actions" || sub.name === "tests")) for (const f of await list(sub.folderId, depth + 1)) out.push({ ...f, path: `${sub.name}/${f.path}` });
      // other folders are the author's own (recorded files, notes): not part of the definition, not read
    }
    return out;
  };
  const tree = await list(folderId, 0);
  const read = async (f: { path: string; fileId: string; version: number }): Promise<string> => {
    const got = (await call("files.read", { fileId: f.fileId, as: "text", length: SOURCE_BOUNDS.fileBytes })) as { text?: string; version?: number; truncated?: boolean };
    if (got.truncated === true || typeof got.text !== "string") return refuse(ctx, "validation.too_large", `${f.path} is too large or is not text.`);
    if (got.version !== undefined && got.version !== f.version) return refuse(ctx, "validation.precondition_failed", `${f.path} changed while the source was being read. Try again.`);
    const size = new TextEncoder().encode(got.text).length;
    bytes += size;
    if (size > SOURCE_BOUNDS.fileBytes || bytes > SOURCE_BOUNDS.bytes) return refuse(ctx, "validation.too_large", `The source of ${key} is too large to read.`);
    return got.text;
  };
  const main = tree.find((f) => f.path === "connector.toml") ?? refuse(ctx, "validation.not_found", `The source of ${key} has no connector.toml.`);
  const mainText = await read(main);
  const docs = async (prefix: "actions/" | "tests/"): Promise<{ path: string; doc: unknown }[]> => {
    const out: { path: string; doc: unknown }[] = [];
    for (const f of tree.filter((x) => x.path.startsWith(prefix) && x.path.endsWith(".json")).sort((a, b) => a.path.localeCompare(b.path))) {
      const text = await read(f);
      try { out.push({ path: f.path, doc: JSON.parse(text) }); } catch { refuse(ctx, "validation.bad_input", `${f.path} is not valid JSON.`); }
    }
    return out;
  };
  const def = buildDef(ctx, key, parseMain(ctx, mainText), await docs("actions/"), await docs("tests/"));
  // a second look at the folder: if any file was added, removed or changed while it was read, the source is not one consistent thing
  const after = await list(folderId, 0).then((x) => x, () => []);
  files = 0;
  const sig = (x: { path: string; fileId: string; version: number }[]): string => x.map((f) => `${f.path}:${f.fileId}:${f.version}`).sort().join("|");
  if (sig(after) !== sig(tree)) refuse(ctx, "validation.precondition_failed", `The source of ${key} changed while it was being read. Try again.`);
  return { def, fingerprint: sig(tree) };
}
