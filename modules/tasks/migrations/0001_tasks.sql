-- tasks: task_meta rows. Status is written only by tasks.transition. Blocked is not a column.
CREATE TABLE IF NOT EXISTS tasks_meta (
  id TEXT PRIMARY KEY,
  kind TEXT NOT NULL,
  assigned TEXT NOT NULL,
  reviewer TEXT,
  approver TEXT,
  taken_by TEXT,
  taken_at INTEGER,
  snoozed_until INTEGER,
  why TEXT,
  blocks TEXT NOT NULL DEFAULT '[]',
  source_kind TEXT,
  source_id TEXT,
  parent_task TEXT,
  depends_on TEXT NOT NULL DEFAULT '[]',
  followers TEXT NOT NULL DEFAULT '[]',
  working_notes TEXT NOT NULL DEFAULT '{}',
  review_loops INTEGER NOT NULL DEFAULT 0,
  decision_id TEXT,
  payload_hash TEXT,
  expires_at INTEGER,
  due INTEGER,
  effort INTEGER,
  thread_id TEXT,
  state TEXT NOT NULL,
  title TEXT NOT NULL,
  summary TEXT,
  created_by TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  file_ids TEXT NOT NULL DEFAULT '[]',
  record_id TEXT,
  actions TEXT NOT NULL DEFAULT '[]',
  bound_device TEXT,
  doc TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS tasks_meta_state ON tasks_meta (state);
CREATE INDEX IF NOT EXISTS tasks_meta_source ON tasks_meta (source_kind, source_id);
