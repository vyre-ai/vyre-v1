/** The label for an input name: its table entry, else its words in sentence case with a trailing "id" left off. */
export function stepInputLabel(name: string): string {
  const own = STEP_INPUT_LABELS[name];
  if (own !== undefined) return own;
  const words = name
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[_.-]+/g, " ")
    .trim()
    .toLowerCase()
    .split(/\s+/)
    .filter((w, i, all) => !(w === "id" && i === all.length - 1 && all.length > 1));
  const text = words.join(" ");
  return text.charAt(0).toUpperCase() + text.slice(1);
}
