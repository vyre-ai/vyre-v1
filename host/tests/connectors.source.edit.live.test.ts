// Editing a connector's source in Files, on a booted daemon over HTTP: edited TOML and recorded tests drive test/diff/publish, a bad edit or a failing test never replaces the last good version, and a Member can
// neither edit nor publish.
import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { bootCore, CORE_SPACE } from "../../fixtures/seed/core/index.ts";
import { startDaemon } from "../src/daemon/daemon.ts";
import { loadConfig } from "../src/daemon/config.ts";
import { fakePlatform } from "../src/platform/index.ts";

test("edited source drives test, diff and publish; a bad edit or failing test keeps the last good version", async () => {
  const core = bootCore(), dir = fs.mkdtempSync(path.join(os.tmpdir(), "vyre-connector-edit-"));
  core.store.db.exec("PRAGMA wal_checkpoint(TRUNCATE); PRAGMA journal_mode=DELETE"); fs.copyFileSync(core.file, path.join(dir, "events.db")); core.close();
  const d = await startDaemon({
    config: loadConfig(["--data-dir", dir, "--port", "0"], {}, "1.2.3"), platform: fakePlatform(),
    session: (headers) => ({ space: CORE_SPACE, principal: { kind: "person", id: headers.authorization === "Bearer owner" ? "usr_olivia" : "usr_noah" }, device: "fixture" }),
    intervals: { fast: 3_600_000, slow: 3_600_000, encryption: 3_600_000, commands: 3_600_000, hooks: 3_600_000 },
  });
  const call = async (token: string, cap: string, input: object): Promise<{ status: number; body: any }> => {   // eslint-disable-line @typescript-eslint/no-explicit-any
    const r = await fetch(`${d.url}/v1/${cap.replaceAll(".", "/")}`, { method: "POST", headers: { authorization: `Bearer ${token}`, "content-type": "application/json" }, body: JSON.stringify(input) });
    return { status: r.status, body: await r.json() };
  };
  const ok = async (cap: string, input: object): Promise<any> => { const r = await call("owner", cap, input); assert.equal(r.status, 200, `${cap}: ${JSON.stringify(r.body)}`); return r.body.data; };   // eslint-disable-line @typescript-eslint/no-explicit-any
  let n = 0; const key = (): string => `edit-${++n}`;
  const toml = (title: string): string => `key = "edited"\ntitle = ${JSON.stringify(title)}\nmode = "api"\nscope = "space"\nversion = "0.0.0"\ndomains = ["api.fixture.test"]\n\n[auth]\ntype = "none"\n`;
  try {
    const init = await ok("connectors.init", { key: "edited", title: "Initial", mode: "webhook_only", idempotencyKey: key() });
    const folder: string = init.folderId;
    const sub = async (name: string): Promise<string> => (await ok("files.folder.create", { parentId: folder, name, idempotencyKey: key() })).folder.folderId;
    const [actions, tests] = [await sub("actions"), await sub("tests")];
    const main = (await ok("files.list", { folder })).files.find((f: { name: string }) => f.name === "connector.toml");
    const edit = async (fileId: string, text: string): Promise<void> => { const cur = (await ok("files.get", { fileId })).file; await ok("files.write", { fileId, baseVersion: cur.version, content: { text }, idempotencyKey: key() }); };
    assert.match((await ok("files.read", { fileId: main.fileId })).text, /^# Generated by Vyre[\s\S]*\ntitle = "Initial"/, "init writes real TOML");
    await edit(main.fileId, toml("Edited"));
    const action = (await ok("files.create", { folderId: actions, name: "ping.json", content: { text: JSON.stringify({ name: "ping", url: "https://api.fixture.test/ping", output: "/ok" }) }, idempotencyKey: key() })).file;
    const spec = (answer: unknown): string => JSON.stringify({ name: "ping", action: "ping", responses: [{ url: "https://api.fixture.test/ping", body: { ok: true } }], expect: { output: answer, requests: 1 } });
    const testFile = (await ok("files.create", { folderId: tests, name: "ping.json", content: { text: spec(true) }, idempotencyKey: key() })).file;

    // TOML the author wrote by hand drives the draft, and publishing uses exactly what was tested
    const published = await ok("connectors.publish", { key: "edited", idempotencyKey: key() });
    assert.equal(published.published, true); assert.equal(published.version, "1.0.0");
    assert.equal((await ok("connectors.get", { key: "edited" })).connector.title, "Edited");

    // a failing recorded test: the publish is refused and the last good version stays live
    await edit(main.fileId, toml("Edited again"));
    await edit(testFile.fileId, spec(false));
    const refused = await ok("connectors.publish", { key: "edited", idempotencyKey: key() });
    assert.equal(refused.published, false, "a failing test does not publish");
    assert.ok(refused.result.failed > 0);
    let live = (await ok("connectors.get", { key: "edited" })).connector;
    assert.deepEqual([live.title, live.version], ["Edited", "1.0.0"], "the last good version is still live");

    // a source that is not valid TOML or JSON fails the call with the file and the reason; still nothing changes
    await edit(testFile.fileId, spec(true));
    await edit(main.fileId, "title = \nmode = ");
    for (const cap of ["connectors.test", "connectors.diff", "connectors.publish"]) {
      const r = await call("owner", cap, { key: "edited", ...(cap === "connectors.publish" ? { idempotencyKey: key() } : {}) });
      assert.ok(r.status >= 400 && /connector\.toml is not valid TOML/.test(JSON.stringify(r.body)), `${cap}: ${JSON.stringify(r.body)}`);
    }
    await edit(action.fileId, "{ not json");
    await edit(main.fileId, toml("Edited"));
    const badAction = await call("owner", "connectors.test", { key: "edited" });
    assert.ok(badAction.status >= 400 && /actions\/ping\.json is not valid JSON/.test(JSON.stringify(badAction.body)), JSON.stringify(badAction.body));
    live = (await ok("connectors.get", { key: "edited" })).connector;
    assert.deepEqual([live.title, live.version], ["Edited", "1.0.0"]);

    // fixed again, a new version is published from the edited files
    await edit(action.fileId, JSON.stringify({ name: "ping", url: "https://api.fixture.test/ping", output: "/ok" }));
    await edit(main.fileId, toml("Edited final"));
    const second = await ok("connectors.publish", { key: "edited", idempotencyKey: key() });
    assert.equal(second.published, true); assert.equal(second.version, "1.0.1");
    assert.equal((await ok("connectors.get", { key: "edited" })).connector.title, "Edited final");

    // a Member can neither edit the source nor publish
    assert.equal((await call("member", "files.write", { fileId: main.fileId, content: { text: toml("Member") }, idempotencyKey: key() })).status, 403);
    assert.ok((await call("member", "connectors.publish", { key: "edited", idempotencyKey: key() })).status >= 400);
    assert.equal((await ok("connectors.get", { key: "edited" })).connector.title, "Edited final");
  } finally { await d.stop(); fs.rmSync(dir, { recursive: true, force: true }); }
});
