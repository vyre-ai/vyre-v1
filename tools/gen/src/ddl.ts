// SQL DDL for synced entities and built-in record types (ARCH 4.3 and 5.10). Server and replica share the same tables.
import type { EntityDef, FieldTypeDef, Owned, RecordTypeDef, Registry } from '../../../packages/contracts/src/index.ts';

export const RT_RESERVED = ['id', 'owner', 'label', 'version', 'created_at', 'updated_at', 'deleted_at', 'holds'];
export const ENTITY_RESERVED = ['id'];
const ENTITY_BASE = ['version', 'updated_at', 'deleted_at'];   // fields with these names map onto the base columns

const q = (s: string) => `"${s.replace(/"/g, '""')}"`;

function columns(fieldKey: string, ft: FieldTypeDef | undefined): Array<{ name: string; sql: string }> {
  if (!ft || !('columns' in ft.storage)) return [];
  return ft.storage.columns.map((c) => ({ name: fieldKey + c.suffix, sql: c.sql }));
}

export function entityTable(e: EntityDef, types: Map<string, FieldTypeDef>): string {
  const cols: string[] = ['  "id" TEXT PRIMARY KEY'];
  for (const [k, f] of Object.entries(e.fields)) {
    if (ENTITY_BASE.includes(k)) continue;
    for (const c of columns(k, types.get(f.type))) cols.push(`  ${q(c.name)} ${c.sql}`);
  }
  cols.push('  "version" INTEGER NOT NULL DEFAULT 0', '  "updated_at" INTEGER', '  "deleted_at" INTEGER');
  const lines = [`CREATE TABLE IF NOT EXISTS ${q(e.table)} (\n${cols.join(',\n')}\n);`, fmTable(e.table)];
  if (e.acl.ownerField && e.acl.ownerField in e.fields) lines.push(`CREATE INDEX IF NOT EXISTS ${q(`${e.table}__owner`)} ON ${q(e.table)} (${q(e.acl.ownerField)});`);
  if (e.acl.parentField && !e.acl.multi && e.acl.parentField in e.fields) lines.push(`CREATE INDEX IF NOT EXISTS ${q(`${e.table}__parent`)} ON ${q(e.table)} (${q(e.acl.parentField)});`);
  return lines.join('\n');
}

function fmTable(table: string): string {
  return `CREATE TABLE IF NOT EXISTS ${q(table + '__fm')} (\n  "id" TEXT NOT NULL,\n  "field" TEXT NOT NULL,\n  "hlc" TEXT NOT NULL,\n  "actor" TEXT,\n  "seq" INTEGER,\n  PRIMARY KEY ("id", "field")\n);`;
}

export function recordTypeTable(r: RecordTypeDef, types: Map<string, FieldTypeDef>): string {
  const table = `rt_${r.key}`;
  const cols: string[] = [
    '  "id" TEXT PRIMARY KEY', '  "owner" TEXT', '  "label" INTEGER NOT NULL DEFAULT 0', '  "version" INTEGER NOT NULL DEFAULT 0',
    '  "created_at" INTEGER', '  "updated_at" INTEGER', '  "deleted_at" INTEGER', '  "holds" INTEGER NOT NULL DEFAULT 0',
  ];
  const idx: string[] = [];
  for (const f of r.fields) {
    const ft = types.get(f.type);
    if (f.key === 'owner' && r.ownerField === 'owner') continue;
    for (const c of columns(f.key, ft)) cols.push(`  ${q(c.name)} ${c.sql}`);
    const hasCol = ft && 'columns' in ft.storage;
    if (hasCol && f.unique) idx.push(`CREATE UNIQUE INDEX IF NOT EXISTS ${q(`${table}__${f.key}__u`)} ON ${q(table)} (${q(f.key)}) WHERE "deleted_at" IS NULL;`);
    else if (hasCol && ft.indexable && (f.key === r.titleField || f.key === r.statusField || f.key === r.summaryField)) idx.push(`CREATE INDEX IF NOT EXISTS ${q(`${table}__${f.key}`)} ON ${q(table)} (${q(f.key)});`);
  }
  idx.push(`CREATE INDEX IF NOT EXISTS ${q(`${table}__owner`)} ON ${q(table)} ("owner");`);
  return [`CREATE TABLE IF NOT EXISTS ${q(table)} (\n${cols.join(',\n')}\n);`, fmTable(table), ...idx].join('\n');
}

export function fieldTypeMap(reg: Registry): Map<string, FieldTypeDef> {
  return new Map(reg.fieldTypes.map((f) => [f.key, f] as const));
}

export function moduleSchemaSql(reg: Registry, moduleId: string): string {
  const types = fieldTypeMap(reg);
  const parts: string[] = [];
  for (const e of reg.entities.filter((x: Owned<EntityDef>) => x.module === moduleId)) parts.push(`-- entity ${e.key}\n${entityTable(e, types)}`);
  for (const r of reg.recordTypes.filter((x: Owned<RecordTypeDef>) => x.module === moduleId)) parts.push(`-- record type ${r.key}\n${recordTypeTable(r, types)}`);
  return parts.length ? `-- GENERATED by tools/gen. Tables of module ${moduleId}; migrations/ add data migrations on top.\n${parts.join('\n\n')}\n` : '';
}

export function replicaSql(reg: Registry): string {
  const types = fieldTypeMap(reg);
  const parts: string[] = ['-- GENERATED by tools/gen. Replica DDL: the same tables as the server, no triggers.'];
  for (const e of reg.entities) if (e.sync.profile.desktop !== 'none' || e.sync.profile.phone !== 'none' || e.sync.profile.web !== 'none') parts.push(`-- entity ${e.key} (${e.module})\n${entityTable(e, types)}`);
  for (const r of reg.recordTypes) parts.push(`-- record type ${r.key} (${r.module})\n${recordTypeTable(r, types)}`);
  return parts.join('\n\n') + '\n';
}
