// Second group of generated outputs: compiled validators, block registry, screen index and probes, sync config, DDL, seeds.
import { readFileSync } from 'node:fs';
import type { Registry } from '../../../packages/contracts/src/index.ts';
import { compileValidators } from './compile.ts';
import { moduleSchemaSql, replicaSql } from './ddl.ts';
import { tsType } from './schema-ts.ts';
import { canonical } from './canonical.ts';

const HEADER = '// GENERATED by tools/gen from manifests/. Do not edit. Run `node tools/gen/src/cli.ts` to regenerate.\n';
const q = (s: string) => JSON.stringify(s);
const sqlStr = (s: string) => `'${s.replace(/'/g, "''")}'`;

interface SeedSpace {
  name: string; domain: string; kind: string;
  people: Array<{ id: string; name: string; role: string; email: string }>;
  clients: Array<{ id: string; name: string; org: string; email: string; phone: string }>;
  agents: string[];
}

export function emitExtras(full: Registry, shared: Registry, put: (p: string, c: string) => void): void {
  put('validators.ts', compileValidators(shared));

  // ---- block registry types
  {
    const lines = [HEADER];
    const map: string[] = [];
    for (const b of full.blocks) {
      const n = b.type.split('_').map((x) => x.charAt(0).toUpperCase() + x.slice(1)).join('');
      lines.push(`export type ${n}BlockData = ${tsType(b.data)};`);
      map.push(`  ${q(b.type)}: ${n}BlockData;`);
    }
    lines.push('', 'export interface BlockDataMap {', ...map, '}', '', 'export type BlockType = keyof BlockDataMap;', '');
    const reg = full.blocks.map((b) => ({
      type: b.type, v: b.v, module: b.module, component: b.component, fallback: b.fallback, waitsForAnswer: b.waitsForAnswer ?? false,
      actions: b.actions ?? [], opens: b.opens ?? null,
    }));
    lines.push(`export const blockRegistry = ${JSON.stringify(reg, null, 2)};`, '');
    lines.push(`/** Fallback text for the CLI, mail and phone notifications. Unknown types render as a generic block with the trace id. */
export function renderFallback(type: string, data: Record<string, unknown>, traceId: string): string {
  const b = blockRegistry.find((x) => x.type === type);
  if (!b) return \`Unknown block \${type} (trace \${traceId})\`;
  return b.fallback.replace(/\\{\\{(\\w+)\\}\\}/g, (_m, k: string) => String(data[k] ?? ''));
}
`);
    put('blocks.ts', lines.join('\n'));
  }

  // ---- screens and probes
  {
    const screens = full.screens.map((s) => ({
      id: s.id, module: s.module, place: s.place, slot: s.slot, builtin: s.builtin ?? null, caller: s.caller ?? 'principal',
      queries: s.queries, actions: s.actions, needs: s.needs ?? [], perf: s.perf ?? null,
    }));
    put('screens.ts', `${HEADER}export interface ScreenIndexEntry {
  id: string; module: string; place: string; slot: string; builtin: string | null; caller: string;
  queries: Record<string, { cap: string; input: Record<string, string>; live: boolean }>;
  actions: Record<string, { cap: string; input: Record<string, string>; confirm?: string }>;
  needs: string[]; perf: { firstPaintMs: number; completeMs: number } | null;
}

export const screens: ScreenIndexEntry[] = ${JSON.stringify(screens, null, 2)};

export const screensById = new Map(screens.map((s) => [s.id, s] as const));
export const screensByPlace = (place: string): ScreenIndexEntry[] => screens.filter((s) => s.place === place);
`);
    const probes = full.screens.filter((s) => s.perf).map((s) => ({ id: `screen.${s.id}`, screen: s.id, place: s.place, firstPaintMs: s.perf?.firstPaintMs, completeMs: s.perf?.completeMs }));
    put('probes.json', canonical({ probes }));
  }

  // ---- sync config and DDL
  {
    const types = new Map(full.fieldTypes.map((f) => [f.key, f] as const));
    const rows: unknown[] = [];
    for (const e of full.entities) {
      rows.push({
        kind: 'entity', key: e.key, table: e.table, idPrefix: e.idPrefix, module: e.module, acl: e.acl, sync: e.sync,
        fields: Object.fromEntries(Object.entries(e.fields).map(([k, f]) => [k, { type: f.type, label: f.label ?? null, required: f.required ?? false }])),
        fts: e.fts ?? [], parent: e.parent ?? null,
      });
    }
    for (const r of full.recordTypes) {
      const protectedFields = r.fields.filter((f) => (f.merge ?? types.get(f.type)?.merge) === 'assistant').map((f) => f.key);
      const text = r.fields.filter((f) => (f.merge ?? types.get(f.type)?.merge) === 'text-crdt').map((f) => f.key);
      rows.push({
        kind: 'record_type', key: r.key, table: `rt_${r.key}`, idPrefix: 'rec_', module: r.module, acl: { resource: 'record', parentField: null, ownerField: r.ownerField ?? null },
        sync: { profile: { desktop: 'all', phone: 'window', web: 'all' }, window: { recentCount: 500, starred: true }, maxLabel: r.label === 'restricted' ? 'confidential' : r.label, protectedFields, text },
        fields: Object.fromEntries(r.fields.map((f) => [f.key, { type: f.type, label: f.label ?? null, required: f.required ?? false }])),
        fts: r.fields.filter((f) => f.key === r.titleField || f.key === r.summaryField).map((f) => f.key), parent: null,
      });
    }
    put('sync/entities.ts', `${HEADER}export interface SyncEntityConfig {
  kind: 'entity' | 'record_type'; key: string; table: string; idPrefix: string; module: string;
  acl: { resource: string; parentField?: string | null; ownerField?: string | null; multi?: boolean; fallback?: { resource: string; field: string } };
  sync: { profile: { desktop: string; phone: string; web: string }; window?: Record<string, unknown>; e2e?: string; maxLabel?: string; text?: string[]; protectedFields?: string[] };
  fields: Record<string, { type: string; label: string | null; required: boolean }>;
  fts: string[]; parent: { entity: string; field: string } | null;
}

export const syncEntities: SyncEntityConfig[] = ${JSON.stringify(rows, null, 2)};

export const syncEntityByKey = new Map(syncEntities.map((e) => [e.key, e] as const));
`);
    put('sync/replica.sql', replicaSql(full));
    for (const m of full.modules) {
      const sql = moduleSchemaSql(full, m.id);
      if (sql) put(`modules/${m.id}/schema.sql`, sql);
    }
  }

  // ---- seeds from the prototype seed
  {
    const seed = JSON.parse(readFileSync(new URL('../seed/spaces.json', import.meta.url), 'utf8')) as { spaces: Record<string, SeedSpace> };
    const roles = ['owner', 'admin', 'developer', 'member', 'guest'];
    const clearance: Record<string, string> = { owner: 'restricted', admin: 'restricted', developer: 'confidential', member: 'internal', guest: 'public' };
    const roleSql: string[] = ['-- built-in roles with the catalogue defaults'];
    for (const r of roles) {
      const perms = full.permissions.filter((p) => p.defaults[r]).map((p) => p.key);
      roleSql.push(`INSERT INTO "access_roles" ("id","name","builtIn","clearance","assignableToAgents","permissions","version") VALUES (${sqlStr('rol_' + r)}, ${sqlStr(r.charAt(0).toUpperCase() + r.slice(1))}, 1, ${sqlStr(clearance[r] as string)}, ${r === 'owner' || r === 'admin' ? 0 : 1}, ${sqlStr(JSON.stringify(perms))}, 1);`);
    }
    put('modules/access/seed.sql', `-- GENERATED by tools/gen. Built-in role rows for every new Space.\n${roleSql.join('\n')}\n`);
    for (const [key, sp] of Object.entries(seed.spaces)) {
      const owner = sp.people.find((p) => p.role === 'owner');
      const lines = [`-- GENERATED by tools/gen from tools/gen/seed/spaces.json. Seed for ${sp.name} (${sp.kind} Space${sp.domain ? ', ' + sp.domain : ''}).`, ...roleSql, '', '-- people'];
      for (const p of sp.people) {
        lines.push(`INSERT INTO "access_principals" ("id","name","kind","owner","status","roles","groups","title","createdAt","version") VALUES (${sqlStr('usr_' + p.id)}, ${sqlStr(p.name)}, 'person', NULL, 'active', ${sqlStr(JSON.stringify(['rol_' + p.role]))}, '[]', ${sqlStr(p.email)}, 1760000000000, 1);`);
      }
      lines.push('', '-- agents');
      for (const a of sp.agents) {
        lines.push(`INSERT INTO "access_principals" ("id","name","kind","owner","status","roles","groups","title","createdAt","version") VALUES (${sqlStr('agt_' + a.toLowerCase())}, ${sqlStr(a)}, 'agent', ${sqlStr('usr_' + (owner?.id ?? ''))}, 'active', '["rol_member"]', '[]', NULL, 1760000000000, 1);`);
      }
      lines.push('', '-- companies and contacts');
      sp.clients.forEach((c, i) => {
        const co = `rec_co${i + 1}`;
        lines.push(`INSERT INTO "rt_company" ("id","owner","label","version","created_at","updated_at","holds","name") VALUES (${sqlStr(co)}, ${sqlStr('usr_' + (owner?.id ?? ''))}, 1, 1, 1760000000000, 1760000000000, 0, ${sqlStr(c.org)});`);
        lines.push(`INSERT INTO "rt_contact" ("id","owner","label","version","created_at","updated_at","holds","name","email","phone","company") VALUES (${sqlStr('rec_' + c.id)}, ${sqlStr('usr_' + (owner?.id ?? ''))}, 1, 1, 1760000000000, 1760000000000, 0, ${sqlStr(c.name)}, ${sqlStr(c.email)}, ${sqlStr(c.phone)}, ${sqlStr(JSON.stringify([co]))});`);
      });
      put(`seed/${key}.sql`, lines.join('\n') + '\n');
    }
  }
}
