// l-shell221: the panel logic live, on the served shots export (run l-shell221-shoot.mjs once first, or drop --skip-export): resize the window across the bands, fold and restore, overlay sheets with Esc and scrim, drag stops, saved widths per band.
//   PLAYWRIGHT_BROWSERS_PATH=/var/lib/ci-run/ms-playwright node scripts/shots/l-shell221-behave.mjs [out-dir]
import fs from "node:fs";
import path from "node:path";
const REPO = process.cwd();
const { serve } = await import(path.join(REPO, "scripts/shots/serve.mjs"));
const { routeUrl } = await import(path.join(REPO, "scripts/shots/lib.mjs"));
const out = process.argv[2] || "/root/wt/tmp-l-shell221/behave";
fs.mkdirSync(out, { recursive: true });
const real = await serve(path.join(REPO, "scripts/shots/app/dist"), { spa: true });
const { createRequire } = await import("node:module");
const { chromium } = createRequire(path.join(REPO, "package.json"))("playwright-core");
const browser = await chromium.launch({ args: ["--no-sandbox"] });
let fails = 0;
const ok = (name, cond, extra = "") => { console.log(`${cond ? "ok  " : "FAIL"} ${name} ${extra}`); if (!cond) fails++; };
const state = (page) => page.evaluate(() => {
  const s = document.querySelector("[data-testid=sheets]");
  const w = (sel) => { const e = document.querySelector(sel); if (!e) return 0; const b = e.getBoundingClientRect(); return b.width < 1 ? 0 : Math.round(b.width); };
  const left = (sel) => { const e = document.querySelector(sel); if (!e) return null; return Math.round(e.getBoundingClientRect().left); };
  return { band: s?.getAttribute("data-band"), sb: s?.getAttribute("data-sidebar"), pane: s?.getAttribute("data-pane"), main: w("[data-testid=sheet-main]"), paneW: w("[data-testid=side-pane]"), sbW: w("[data-testid=place-sidebar]"), sbLeft: left("[data-testid=place-sidebar]"), scrim: !!document.querySelector("[data-testid=sheet-scrim]"), mainLeft: left("[data-testid=sheet-main]") };
});
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "dark", reducedMotion: "reduce" });
const page = await ctx.newPage();
await page.goto(routeUrl(real.origin, "/m/SHELL221_01?place=chats&pane=0", "graphite"), { waitUntil: "load" });
await page.waitForSelector("[data-testid=shell-rail]"); await page.waitForTimeout(500);
const settle = () => page.waitForTimeout(450);
let s = await state(page);
ok("1440 sidebar docked, no pane", s.band === "wide" && s.sb === "docked" && s.pane === "none", JSON.stringify(s));
await page.click("[data-testid=open-pane]"); await settle();
s = await state(page);
ok("1440 pane opens beside main, main keeps 480", s.pane === "docked" && s.main >= 480 && s.paneW >= 360, JSON.stringify(s));
await page.setViewportSize({ width: 1100, height: 800 }); await settle();
s = await state(page);
ok("1100 with the pane open: sidebar folds to the rail", s.band === "mid" && s.sb === "hidden" && s.pane === "docked" && s.main >= 480, JSON.stringify(s));
await page.screenshot({ path: path.join(out, "mid-folded.png") });
await page.evaluate(() => window.__pane(false)); await settle();
s = await state(page);
ok("1100 pane closed: sidebar comes back", s.sb === "docked" && s.pane === "none", JSON.stringify(s));
await page.click("[data-testid=open-pane]"); await settle();
await page.click("[data-testid=sidebar-expand]"); await settle();
s = await state(page);
ok("1100 folded sidebar opened from its button is an overlay, the pane stays", s.sb === "overlay" && s.pane === "docked", JSON.stringify(s));
await page.screenshot({ path: path.join(out, "mid-sidebar-peek.png") });
await page.keyboard.press("Escape"); await settle();
s = await state(page);
ok("Escape puts the overlay sidebar away", s.sb === "hidden" && s.pane === "docked", JSON.stringify(s));
await page.setViewportSize({ width: 900, height: 800 }); await settle();
s = await state(page);
ok("900 the pane is an overlay sheet with a scrim; main keeps the room", s.band === "sheet" && s.pane === "overlay" && s.scrim && s.main > 800, JSON.stringify(s));
await page.keyboard.press("Escape"); await settle();
s = await state(page);
ok("Escape closes the overlay pane", s.pane === "none" && !s.scrim, JSON.stringify(s));
await page.click("[data-testid=sidebar-expand]"); await settle();
s = await state(page);
ok("900 the sidebar opens as an overlay over main, from main's left edge", s.sb === "overlay" && s.scrim && s.sbLeft === s.mainLeft, JSON.stringify(s));
await page.screenshot({ path: path.join(out, "sheet-sidebar.png") });
await page.click("[data-testid=sheet-scrim]", { position: { x: 700, y: 400 } }); await settle();
s = await state(page);
ok("a click on the scrim closes it", s.sb === "hidden" && !s.scrim, JSON.stringify(s));
await page.setViewportSize({ width: 700, height: 800 }); await settle();
ok("700 is one panel at a time (no rail column)", (await page.locator("[data-testid=shell-rail-bottom]").count()) === 1);
await page.setViewportSize({ width: 1440, height: 900 }); await settle();
s = await state(page);
ok("back to 1440: everything docked again", s.band === "wide" && s.sb === "docked", JSON.stringify(s));
// drags
await page.click("[data-testid=open-pane]"); await settle();
const drag = async (sel, dx) => { const b = await page.locator(sel).boundingBox(); const x = b.x + b.width / 2, y = b.y + 300; await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + dx / 2, y, { steps: 6 }); await page.mouse.move(x + dx, y, { steps: 6 }); await page.mouse.up(); await settle(); };
await drag("[data-testid=side-pane-resize]", -600);
s = await state(page);
ok("dragging the pane far left stops with main at 480", s.main >= 479 && s.main <= 481 && s.paneW <= 640, JSON.stringify(s));
await drag("[data-testid=side-pane-resize]", 900);
s = await state(page);
ok("dragging the pane far right stops at 320", s.paneW === 320, JSON.stringify(s));
await drag("[data-testid=sidebar-resize]", 600);
s = await state(page);
ok("dragging the sidebar far right stops at 360 and main stays over 480", s.sbW === 360 && s.main >= 480, JSON.stringify(s));
await drag("[data-testid=sidebar-resize]", -600);
s = await state(page);
ok("dragging the sidebar far left stops at 220", s.sbW === 220, JSON.stringify(s));
// saved per band
await drag("[data-testid=side-pane-resize]", -60); const wide = (await state(page)).paneW;
await page.setViewportSize({ width: 1100, height: 800 }); await settle();
const midW = (await state(page)).paneW;
ok("the pane width saved at 1440 is not the width at 1100 (bands keep their own)", wide !== midW, `wide=${wide} mid=${midW}`);
await page.setViewportSize({ width: 1440, height: 900 }); await settle();
ok("back at 1440 the saved width returns", (await state(page)).paneW === wide, `${(await state(page)).paneW} vs ${wide}`);
await ctx.close(); await browser.close(); real.close();
console.log(fails === 0 ? "ALL BEHAVIOURS OK" : `${fails} FAILED`);
process.exit(fails === 0 ? 0 : 1);
