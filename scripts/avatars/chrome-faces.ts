// Writes apps/chrome/src/ui/faces.js: the 96 drawn faces (idle, no tint) the Chrome side panel draws, from the same curated lists the app uses (ui/src/Avatar/library.ts), so the extension needs no DiceBear.
// Run on the build box: node --import tsx scripts/avatars/chrome-faces.ts   (apps/chrome/tests/ext-faces.test.ts fails when the file is out of date.)
import fs from "node:fs";
import path from "node:path";
import { DRAWN, EMOJI, PER_FAMILY, TINTS } from "../../ui/src/Avatar/agentface.ts";
import { faceSvg } from "../../ui/src/Avatar/library.ts";

export function build(): string {
  const faces: Record<string, string[]> = {};
  for (const fam of DRAWN) {
    faces[fam] = Array.from({ length: PER_FAMILY }, (_, i) => faceSvg({ fam, i, tint: 0 }, "idle", 64).replace(/<rect [^>]*\/>/, "").replace(/ width="64" height="64"/, ""));
  }
  return `// GENERATED by scripts/avatars/chrome-faces.ts from ui/src/Avatar/library.ts. Do not edit. The drawn faces (idle, no tint) the Chrome panel draws, the tints they sit on and the emoji.\n`
    + `export const FACE_TINTS = ${JSON.stringify(TINTS.map((t) => t.hex))};\nexport const FACE_EMOJI = ${JSON.stringify(EMOJI)};\nexport const FACE_SVGS = ${JSON.stringify(faces)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = path.resolve(import.meta.dirname, "../../apps/chrome/src/ui/faces.js");
  fs.writeFileSync(out, build());
  console.log("wrote", out);
}
